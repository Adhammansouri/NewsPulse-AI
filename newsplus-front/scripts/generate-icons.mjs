// Generates src/ui/icons.ts from docs/redesign/design/icons.json (the Pulse icon set).
// Usage: node scripts/generate-icons.mjs   (run from newsplus-front, or anywhere — paths are resolved from this file)
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const frontDir = path.resolve(scriptDir, "..");
const source = path.resolve(frontDir, "..", "docs", "redesign", "design", "icons.json");
const target = path.join(frontDir, "src", "ui", "icons.ts");

const json = JSON.parse(await readFile(source, "utf8"));
const { icons, sizes, viewBox, strokeWidth } = json;

if (!icons || typeof icons !== "object") throw new Error(`No "icons" map in ${source}`);
if (!sizes || typeof sizes !== "object") throw new Error(`No "sizes" map in ${source}`);

const names = Object.keys(icons);
for (const name of names) {
  if (typeof icons[name] !== "string" || !icons[name].trim()) throw new Error(`Icon "${name}" has no path data`);
}

const q = (value) => JSON.stringify(value);
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : q(name));

const lines = [
  "// AUTO-GENERATED by scripts/generate-icons.mjs from docs/redesign/design/icons.json.",
  "// Do not edit by hand: change icons.json and re-run `node scripts/generate-icons.mjs`.",
  "",
  `export const ICON_VIEWBOX = ${q(viewBox)};`,
  "",
  `export const ICON_STROKE_WIDTH = ${strokeWidth};`,
  "",
  "export const ICON_SIZES = {",
  ...Object.entries(sizes).map(([size, px]) => `  ${key(size)}: ${px},`),
  "} as const;",
  "",
  "export type IconSize = keyof typeof ICON_SIZES;",
  "",
  "export type IconName =",
  ...names.map((name, i) => `  | ${q(name)}${i === names.length - 1 ? ";" : ""}`),
  "",
  "export const ICON_PATHS: Readonly<Record<IconName, string>> = {",
  ...names.map((name) => `  ${key(name)}: ${q(icons[name])},`),
  "};",
  "",
  "export const ICON_NAMES = Object.keys(ICON_PATHS) as IconName[];",
  "",
];

await writeFile(target, lines.join("\n"), "utf8");
process.stdout.write(`Wrote ${names.length} icons to ${path.relative(frontDir, target)}\n`);
